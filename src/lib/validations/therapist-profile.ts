import { z } from "zod";
import { availabilityStatusSchema } from "./enums";
import { serviceOfferingSchema } from "./service-offering";

export const therapistProfileSchema = z.object({
  id: z.string().min(1),
  userId: z.string().min(1),
  displayName: z.string().min(1).max(120),
  photoUrl: z.string().max(2048).nullable(),
  bio: z.string().max(4000).nullable(),
  yearsExperience: z.number().int().min(0).max(60).nullable(),
  licenseNumber: z.string().max(64).nullable(),
  licenseVerified: z.boolean(),
  insuranceVerified: z.boolean(),
  licenseDocumentUrl: z.string().nullable(),
  insuranceDocumentUrl: z.string().nullable(),
  specialties: z.array(z.string().min(1)).max(24),
  certifications: z.array(z.string().min(1)).max(32),
  services: z.array(serviceOfferingSchema).min(1),
  travelRadiusMiles: z.number().positive().max(120),
  acceptsHome: z.boolean(),
  acceptsHotel: z.boolean(),
  acceptsOffice: z.boolean(),
  acceptsEvents: z.boolean(),
  acceptsValetJobs: z.boolean(),
  availabilityStatus: availabilityStatusSchema,
  ratingAverage: z.number().min(0).max(5),
  ratingCount: z.number().int().nonnegative(),
  isApproved: z.boolean(),
  city: z.string().nullable(),
  state: z.string().max(2).nullable(),
  active: z.boolean(),
  createdAt: z.string(),
  updatedAt: z.string(),
});

export const therapistProfileSummarySchema = therapistProfileSchema.pick({
  id: true,
  userId: true,
  displayName: true,
  photoUrl: true,
  specialties: true,
  yearsExperience: true,
  availabilityStatus: true,
  ratingAverage: true,
  ratingCount: true,
  licenseVerified: true,
  insuranceVerified: true,
  travelRadiusMiles: true,
  acceptsHome: true,
  acceptsHotel: true,
  acceptsOffice: true,
  acceptsEvents: true,
  active: true,
  isApproved: true,
}).extend({
  priceStartingAt: z.number().nonnegative().nullable(),
  distanceMiles: z.number().nonnegative().nullable(),
});
